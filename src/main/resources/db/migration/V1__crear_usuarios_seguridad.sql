CREATE TABLE modulo (
    id_modulo INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    orden INTEGER NOT NULL,
    CONSTRAINT pk_modulo PRIMARY KEY (id_modulo)
);

CREATE TABLE rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(120) NOT NULL,
    ambito VARCHAR(30) NOT NULL,
    es_sistema BOOLEAN NOT NULL,
    activo BOOLEAN NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol)
);

CREATE TABLE permiso (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_modulo INTEGER NOT NULL,
    codigo VARCHAR(80) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    asignable BOOLEAN NOT NULL,
    CONSTRAINT pk_permiso PRIMARY KEY (id_permiso),
    CONSTRAINT fk_permiso_modulo FOREIGN KEY (id_modulo) REFERENCES modulo (id_modulo)
);

CREATE TABLE usuario (
    id_usuario UUID,
    id_rol INTEGER NOT NULL,
    tipo_cuenta VARCHAR(30) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    apellido VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    telefono VARCHAR(30),
    password_hash VARCHAR(255) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol)
);

CREATE TABLE rol_permiso (
    id_rol INTEGER NOT NULL,
    id_permiso INTEGER NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (id_rol, id_permiso),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (id_permiso) REFERENCES permiso (id_permiso)
);

CREATE TABLE restriccion_usuario (
    id_restriccion UUID,
    id_usuario UUID NOT NULL,
    id_permiso INTEGER NOT NULL,
    id_administrador UUID NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ,
    activa BOOLEAN NOT NULL,
    CONSTRAINT pk_restriccion_usuario PRIMARY KEY (id_restriccion),
    CONSTRAINT fk_restriccion_recibe_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_restriccion_restringe_permiso FOREIGN KEY (id_permiso) REFERENCES permiso (id_permiso),
    CONSTRAINT fk_restriccion_aplica_administrador FOREIGN KEY (id_administrador) REFERENCES usuario (id_usuario)
);

CREATE INDEX idx_permiso_modulo ON permiso (id_modulo);
CREATE INDEX idx_usuario_rol ON usuario (id_rol);
CREATE INDEX idx_rol_permiso_permiso ON rol_permiso (id_permiso);
CREATE INDEX idx_restriccion_usuario ON restriccion_usuario (id_usuario);
CREATE INDEX idx_restriccion_permiso ON restriccion_usuario (id_permiso);
CREATE INDEX idx_restriccion_administrador ON restriccion_usuario (id_administrador);
