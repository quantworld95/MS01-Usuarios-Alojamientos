CREATE TABLE tipo_propiedad (
    id_tipo_propiedad INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT pk_tipo_propiedad PRIMARY KEY (id_tipo_propiedad)
);

CREATE UNIQUE INDEX uq_tipo_propiedad_nombre ON tipo_propiedad (lower(nombre));

CREATE TABLE tipo_espacio (
    id_tipo_espacio INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT pk_tipo_espacio PRIMARY KEY (id_tipo_espacio)
);

CREATE UNIQUE INDEX uq_tipo_espacio_nombre ON tipo_espacio (lower(nombre));

CREATE TABLE servicio (
    id_servicio INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio)
);

CREATE TABLE alojamiento (
    id_alojamiento UUID,
    id_anfitrion UUID NOT NULL,
    id_tipo_propiedad INTEGER NOT NULL,
    titulo VARCHAR(140) NOT NULL,
    descripcion TEXT NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    departamento VARCHAR(40) NOT NULL,
    latitud NUMERIC(9, 6) NOT NULL,
    longitud NUMERIC(9, 6) NOT NULL,
    estado_publicacion VARCHAR(30) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_alojamiento PRIMARY KEY (id_alojamiento),
    CONSTRAINT fk_alojamiento_anfitrion FOREIGN KEY (id_anfitrion) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_alojamiento_tipo_propiedad FOREIGN KEY (id_tipo_propiedad) REFERENCES tipo_propiedad (id_tipo_propiedad)
);

CREATE TABLE fotografia (
    id_fotografia UUID,
    id_alojamiento UUID NOT NULL,
    url VARCHAR(500) NOT NULL,
    orden INTEGER NOT NULL,
    CONSTRAINT pk_fotografia PRIMARY KEY (id_fotografia),
    CONSTRAINT uq_fotografia_orden UNIQUE (id_alojamiento, orden),
    CONSTRAINT fk_fotografia_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento)
);

CREATE TABLE alojamiento_servicio (
    id_alojamiento UUID NOT NULL,
    id_servicio INTEGER NOT NULL,
    CONSTRAINT pk_alojamiento_servicio PRIMARY KEY (id_alojamiento, id_servicio),
    CONSTRAINT fk_alojamiento_servicio_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT fk_alojamiento_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES servicio (id_servicio)
);

CREATE TABLE unidad_reservable (
    id_unidad UUID,
    id_alojamiento UUID NOT NULL,
    id_tipo_espacio INTEGER NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    capacidad_huespedes INTEGER NOT NULL,
    cantidad_dormitorios INTEGER NOT NULL,
    cantidad_camas INTEGER NOT NULL,
    cantidad_banos NUMERIC(3, 1) NOT NULL,
    inventario_total INTEGER NOT NULL,
    precio_noche NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT pk_unidad_reservable PRIMARY KEY (id_unidad),
    CONSTRAINT fk_unidad_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT fk_unidad_tipo_espacio FOREIGN KEY (id_tipo_espacio) REFERENCES tipo_espacio (id_tipo_espacio)
);

CREATE TABLE historial_publicacion (
    id_historial UUID,
    id_alojamiento UUID NOT NULL,
    estado VARCHAR(30) NOT NULL,
    motivo VARCHAR(500),
    id_actor UUID NOT NULL,
    fecha TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_historial_publicacion PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
    CONSTRAINT fk_historial_actor FOREIGN KEY (id_actor) REFERENCES usuario (id_usuario)
);

CREATE INDEX idx_alojamiento_anfitrion ON alojamiento (id_anfitrion);
CREATE INDEX idx_alojamiento_tipo_propiedad ON alojamiento (id_tipo_propiedad);
CREATE INDEX idx_alojamiento_estado ON alojamiento (estado_publicacion);
CREATE INDEX idx_fotografia_alojamiento ON fotografia (id_alojamiento);
CREATE INDEX idx_unidad_alojamiento ON unidad_reservable (id_alojamiento);
CREATE INDEX idx_unidad_tipo_espacio ON unidad_reservable (id_tipo_espacio);
CREATE INDEX idx_historial_alojamiento ON historial_publicacion (id_alojamiento);
CREATE INDEX idx_alojamiento_servicio_servicio ON alojamiento_servicio (id_servicio);
